"""Generate the Lean module dependency diagrams on the Lean verification page.

The Mermaid diagrams in ``website/lean-verification.qmd`` are generated from the
actual ``import MixedSignCoxeter.*`` lines in ``lean/MixedSignCoxeter/*.lean``
and the statement index in ``original/mixed_sign_coxeter_statements_lean.csv``,
so neither edges nor captions can drift from the code.  Modules are partitioned
into four views: an overview graph has one node per view with cross-view imports
as edge labels, and each view draws its own modules together with dashed stub
nodes for any direct upstream imports from other views so no module appears
disconnected.

Usage::

    python scripts/lean_module_graph.py          # rewrite the diagrams in place
    python scripts/lean_module_graph.py --check  # exit 1 if the page is stale

``tests/test_lean_module_graph.py`` runs the check in CI.
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEAN_DIR = ROOT / "lean" / "MixedSignCoxeter"
ROOT_MODULE = ROOT / "lean" / "MixedSignCoxeter.lean"
STATEMENTS_CSV = ROOT / "original" / "mixed_sign_coxeter_statements_lean.csv"
PAGE = ROOT / "website" / "lean-verification.qmd"
BEGIN = "<!-- BEGIN lean-module-graph (generated by scripts/lean_module_graph.py; do not edit) -->"
END = "<!-- END lean-module-graph -->"

_TYPE_ABBR: dict[str, str] = {
    "Theorem": "Thm",
    "Proposition": "Prop",
    "Lemma": "Lem",
    "Corollary": "Cor",
    "Question": "Q",
    "Example": "Ex",
    "Remark": "Rem",
    "Definition": "Def",
}
_TYPE_PRIORITY: list[str] = [
    "Theorem",
    "Proposition",
    "Corollary",
    "Lemma",
    "Question",
    "Example",
    "Remark",
    "Definition",
]

# Short captions for modules not mapped in original/mixed_sign_coxeter_statements_lean.csv
# (post-dissertation cycle-family extensions and the split half of Theorem 3.9).
FALLBACK_LABELS: dict[str, str] = {
    "CoxeterPresentation": "Thm 3.9: Deletion ⇒ Coxeter",
    "OddCycleSingleDefect": "C₂ₘ₊₁(+,−,…,−)",
    "EvenCycleSingleDefect": "C₂ₘ(+,−,…,−): ∃λ ∈ (−5, −1)",
    "BipartiteDuality": "bipartite sign-flip duality",
    "TwoDefectCycle": "Cₙ(+,+,−,…,−): ρ(w) &gt; 1",
}


def _format_csv_caption(items: list[tuple[str, str]], limit: int = 4) -> str:
    """Summarize a module's dissertation statements into a compact box caption."""
    ordered = sorted(
        items,
        key=lambda x: (_TYPE_PRIORITY.index(x[0]), [int(p) for p in x[1].split(".")]),
    )
    shown = ordered[:limit]
    extra = len(ordered) - len(shown)
    groups: dict[str, list[str]] = defaultdict(list)
    for typ, num in shown:
        groups[typ].append(num)
    text = "; ".join(f"{_TYPE_ABBR[t]} {', '.join(nums)}" for t, nums in groups.items())
    if extra > 0:
        text += f" (+{extra} more)"
    return text


def module_labels() -> dict[str, str]:
    """Generate short captions from STATEMENTS_CSV, falling back to FALLBACK_LABELS."""
    by_mod: dict[str, list[tuple[str, str]]] = defaultdict(list)
    with STATEMENTS_CSV.open(newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            lean_file = (row.get("lean_file") or "").strip()
            for part in lean_file.split(";"):
                part = part.strip()
                if part:
                    by_mod[Path(part).stem].append((row["type"], row["number"]))
    labels = dict(FALLBACK_LABELS)
    for mod, items in by_mod.items():
        labels[mod] = _format_csv_caption(items)
    return labels


LABELS: dict[str, str] = module_labels()

# (heading, modules) for each view.  Every module must appear in exactly one view.
VIEWS: list[tuple[str, list[str]]] = [
    ("1. Foundations, Mixed Signs & Rank Two",
     ["ReflectionSystem", "Bipartite", "MixedSign", "RankTwo", "RankTwoRoots", "FiniteReduction"]),
    ("2. Conjugacy & Graph Structure: Components, Trees & Odd Cycles",
     ["Conjugacy", "ComponentsAndTrees", "TreeConjugacy", "OddCycles"]),
    ("3. Coxeter Presentation, Deletion, & Cycles ",
     ["CyclesAndDeletion", "ParabolicTransfer", "ClassicalDeletion", "CoxeterPresentation",
      "ClassicalCoxeterDeletion", "RootPositivity", "RemarksAndClassical",
      "TildeAminusEvenIso"]),
    ("4. Howlett Matrix & Cycle Families",
     ["Howlett",
      "OddCycleSingleDefect", "EvenCycleSingleDefect", "BipartiteDuality", "TwoDefectCycle"]),
    ("5. Spectral Radius",
     ["SpectralRadius", "SpectralClassification", "AlternatingSquare"])  
]

_IMPORT = re.compile(r"(?m)^import\s+MixedSignCoxeter\.(\w+)\s*$")


def module_imports() -> dict[str, list[str]]:
    """Map each module to the project modules it imports directly."""
    return {
        path.stem: _IMPORT.findall(path.read_text(encoding="utf-8"))
        for path in sorted(LEAN_DIR.glob("*.lean"))
    }


def validate(imports: dict[str, list[str]]) -> list[str]:
    errors = []
    placed = [m for _, mods in VIEWS for m in mods]
    for mod in sorted(set(imports) - set(placed)):
        errors.append(f"module {mod} is not assigned to a view in scripts/lean_module_graph.py")
    for mod in sorted(set(placed) - set(imports)):
        errors.append(f"view lists {mod}, but lean/MixedSignCoxeter/{mod}.lean does not exist")
    dupes = {m for m in placed if placed.count(m) > 1}
    errors.extend(f"module {m} appears in more than one view" for m in sorted(dupes))
    root_imports = set(_IMPORT.findall(ROOT_MODULE.read_text(encoding="utf-8")))
    for mod in sorted(set(imports) - root_imports):
        errors.append(f"lean/MixedSignCoxeter.lean does not import MixedSignCoxeter.{mod}")
    for mod, deps in imports.items():
        for dep in deps:
            if dep not in imports:
                errors.append(f"{mod}.lean imports missing module MixedSignCoxeter.{dep}")
    return errors


def view_of(imports: dict[str, list[str]]) -> dict[str, int]:
    """Map each module to the index of the view it belongs to."""
    return {mod: i for i, (_, mods) in enumerate(VIEWS) for mod in mods}


def render_overview(imports: dict[str, list[str]]) -> str:
    """One node per view; each edge lists the imports that cross between views."""
    where = view_of(imports)
    crossing: dict[tuple[int, int], list[str]] = {}
    for mod, deps in imports.items():
        for dep in deps:
            if where[dep] != where[mod]:
                crossing.setdefault((where[dep], where[mod]), []).append(f"{dep} → {mod}")
    lines = ["```{mermaid}", "flowchart LR"]
    for i, (heading, mods) in enumerate(VIEWS):
        title = heading.split(". ", 1)[-1]
        lines.append(f'  V{i + 1}["<b>{i + 1}. {title}</b><br/>{len(mods)} modules"]')
    for (src, dst), pairs in sorted(crossing.items()):
        lines.append(f'  V{src + 1} -->|"{"<br/>".join(sorted(pairs))}"| V{dst + 1}')
    lines.append("```")
    return "\n".join(lines)


def render_view(
    modules: list[str],
    imports: dict[str, list[str]],
    where: dict[str, int],
) -> str:
    """Modules of one view, plus dashed stubs for direct upstream cross-view imports."""
    inside = set(modules)
    externals = sorted({dep for mod in modules for dep in imports[mod] if dep not in inside})
    lines = ["```{mermaid}", "flowchart TB"]
    if externals:
        lines.append("  classDef ext stroke-dasharray: 5 5")
        for dep in externals:
            lines.append(f'  ext_{dep}(["{dep}.lean<br/>(View {where[dep] + 1})"])')
    for mod in modules:
        label = f"{mod}.lean<br/>{LABELS[mod]}" if mod in LABELS else f"{mod}.lean"
        lines.append(f'  {mod}["{label}"]')
    for mod in modules:
        for dep in imports[mod]:
            if dep in inside:
                lines.append(f"  {dep} --> {mod}")
            else:
                lines.append(f"  ext_{dep} -.-> {mod}")
    if externals:
        lines.append(f"  class {','.join(f'ext_{dep}' for dep in externals)} ext")
    lines.append("```")
    return "\n".join(lines)


def render(imports: dict[str, list[str]]) -> str:
    total = sum(len(v) for v in imports.values())
    where = view_of(imports)
    parts = [
        BEGIN,
        "",
        f"These diagrams are generated from the `import` lines of all {len(imports)} modules "
        f"({total} direct imports between them). Each module belongs to one view. "
        "The overview shows how the four views connect; each view below shows its own modules "
        "(solid boxes and arrows) along with dashed stubs for direct upstream imports from other views.",
        "",
        "### Overview",
        "",
        render_overview(imports),
    ]
    for heading, modules in VIEWS:
        parts += ["", f"### {heading}", "", render_view(modules, imports, where)]
    parts += ["", END]
    return "\n".join(parts)


def updated_page(text: str, block: str) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{PAGE} is missing the generated-block markers")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the page is stale")
    args = parser.parse_args(argv)

    imports = module_imports()
    errors = validate(imports)
    for err in errors:
        print(f"error: {err}", file=sys.stderr)
    if errors:
        return 1
    text = PAGE.read_text(encoding="utf-8")
    new = updated_page(text, render(imports))
    if new == text:
        return 0
    if args.check:
        print(f"{PAGE.relative_to(ROOT)} is stale; run python scripts/lean_module_graph.py",
              file=sys.stderr)
        return 1
    PAGE.write_text(new, encoding="utf-8")
    print(f"updated {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
