"""Explicit isomorphisms W(~A_{-n}) = W(D_{n+1}) and the Appendix D presentation.

Section 1.4 of Armstrong (2012) remarks that for n = 2, 4, 6 the groups W(~A_{-n})
"are isomorphic to W(D_{n+1})"; the repository previously only compared group
orders. This module upgrades that to an explicit isomorphism, valid for *every*
even n >= 2, and reproduces the GAP computation of Appendix D in pure Python.

Construction (all arithmetic is exact integer arithmetic)
--------------------------------------------------------
Let B = B(~A_{-n}) (odd cycle of n + 1 negative nodes, n even). The generating
reflections are s_i(v) = v - (2 B(v, e_i) / B(e_i, e_i)) e_i = v - Q(v, e_i) e_i
with Q = -B, so W(~A_{-n}) is the reflection group of the norm-2 vectors e_i in
the positive definite lattice (Z^{n+1}, Q). Take, in R^{n+1} with the dot product
and standard basis eps_1, ..., eps_{n+1},

    r_i = (-1)^i (eps_{i+1} - eps_{i+2})   for 0 <= i <= n - 1,
    r_n = eps_1 + eps_{n+1}.

These are roots of D_{n+1} whose Gram matrix is exactly Q, so the integer matrix
T = [r_0 | ... | r_n] satisfies T^T T = Q and det T = +-2. Consequently
T s_i T^{-1} is the orthogonal reflection in r_i, and conjugation by T is an
injective homomorphism W(~A_{-n}) -> O(n + 1). Its image is generated by
reflections in roots of D_{n+1}, and the orbit of {r_i} under those reflections
is the whole D_{n+1} root system (checked below), so the image contains the
reflection in every D_{n+1} root, in particular in every standard simple root.
Hence the image is exactly W(D_{n+1}) and w -> T w T^{-1} is an isomorphism.
"""

from __future__ import annotations

from dataclasses import dataclass
from itertools import combinations

import numpy as np
import sympy as sp

from .mixed_sign import MixedSignCoxeterGraph


def _int_generators(g: MixedSignCoxeterGraph) -> list[np.ndarray]:
    out = []
    for s in g.generators():
        arr = np.array(s.tolist(), dtype=object)
        out.append(np.array([[int(v) for v in row] for row in arr], dtype=np.int64))
    return out


def d_root_system(rank: int) -> set[tuple[int, ...]]:
    """Roots of D_rank: +-eps_i +- eps_j (i < j), as integer tuples."""
    roots: set[tuple[int, ...]] = set()
    for i, j in combinations(range(rank), 2):
        for a in (1, -1):
            for b in (1, -1):
                v = [0] * rank
                v[i], v[j] = a, b
                roots.add(tuple(v))
    return roots


def d_simple_roots(rank: int) -> list[tuple[int, ...]]:
    """Standard simple roots eps_i - eps_{i+1} (i < rank) and eps_{rank-1} + eps_rank."""
    out = []
    for i in range(rank - 1):
        v = [0] * rank
        v[i], v[i + 1] = 1, -1
        out.append(tuple(v))
    v = [0] * rank
    v[rank - 2], v[rank - 1] = 1, 1
    out.append(tuple(v))
    return out


def a_tilde_minus_to_d_roots(n: int) -> list[tuple[int, ...]]:
    """The roots r_0, ..., r_n of D_{n+1} that the generators of W(~A_{-n}) map to."""
    if n < 2 or n % 2:
        raise ValueError("n must be even and >= 2.")
    dim = n + 1
    roots = []
    for i in range(n):
        v = [0] * dim
        sgn = 1 if i % 2 == 0 else -1
        v[i], v[i + 1] = sgn, -sgn
        roots.append(tuple(v))
    v = [0] * dim
    v[0], v[n] = 1, 1
    roots.append(tuple(v))
    return roots


def orthogonal_reflection(r: tuple[int, ...]) -> np.ndarray:
    """Matrix of x -> x - (x . r) r for a norm-2 integer vector r."""
    rv = np.array(r, dtype=np.int64).reshape(-1, 1)
    return np.eye(len(r), dtype=np.int64) - rv @ rv.T


@dataclass(frozen=True)
class IsomorphismCertificate:
    n: int
    gram_matches: bool
    det_T: int
    conjugates_generators: bool
    root_orbit_is_D: bool
    contains_D_simple_reflections: bool
    order_W_D: int

    @property
    def is_isomorphism(self) -> bool:
        return (
            self.gram_matches
            and self.det_T != 0
            and self.conjugates_generators
            and self.root_orbit_is_D
            and self.contains_D_simple_reflections
        )


def verify_a_tilde_minus_isomorphism(n: int) -> IsomorphismCertificate:
    """Certify W(~A_{-n}) = W(D_{n+1}) via the explicit conjugating matrix T (n even)."""
    g = MixedSignCoxeterGraph.A_tilde(n, negative=True)
    dim = n + 1
    roots = a_tilde_minus_to_d_roots(n)
    T = sp.Matrix([list(r) for r in roots]).T  # columns are r_i
    Q = -g.B
    gram_ok = (T.T * T - Q) == sp.zeros(dim, dim)
    det_T = int(T.det())

    # T s_i T^{-1} == orthogonal reflection in r_i, checked as T s_i == R_i T (exact).
    conj_ok = True
    for i, s in enumerate(g.generators()):
        R = sp.Matrix(orthogonal_reflection(roots[i]).tolist())
        if T * s != R * T:
            conj_ok = False

    # Orbit of {r_i} under the reflections in r_i.
    refl = [orthogonal_reflection(r) for r in roots]
    orbit = set(roots)
    frontier = list(roots)
    while frontier:
        new = []
        for v in frontier:
            vv = np.array(v, dtype=np.int64)
            for R in refl:
                w = tuple(int(t) for t in R @ vv)
                if w not in orbit:
                    orbit.add(w)
                    new.append(w)
        frontier = new
    D = d_root_system(dim)
    orbit_ok = orbit == D
    simple_ok = all(r in orbit for r in d_simple_roots(dim))
    order = (2 ** (dim - 1)) * int(sp.factorial(dim))
    return IsomorphismCertificate(
        n=n,
        gram_matches=bool(gram_ok),
        det_T=det_T,
        conjugates_generators=conj_ok,
        root_orbit_is_D=orbit_ok,
        contains_D_simple_reflections=simple_ok,
        order_W_D=order,
    )


def a_tilde_minus_is_finite(n: int) -> bool:
    """W(~A_{-n}) is finite iff n is even.

    n even: isomorphic to W(D_{n+1}) (verify_a_tilde_minus_isomorphism).
    n odd: the cycle has an even number of nodes, so it is bipartite, and by
    Theorem 1.4 W(~A_{-n}) is conjugate to the affine group W(~A_n), which is infinite.
    """
    if n < 2:
        raise ValueError("n >= 2 required.")
    return n % 2 == 0


